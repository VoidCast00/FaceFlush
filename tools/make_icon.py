"""Generates the FaceFlush launcher icon: a face made of pixel noise with a glitch band over the eyes.

Usage: python3 tools/make_icon.py app/src/main/res/drawable [preview.png]
Writes the adaptive icon's background, foreground and monochrome layers as vector drawables.
"""
import random, sys
from PIL import Image, ImageDraw

OUT = sys.argv[1]
CELL = 4  # dp; 27 x 27 cells over the 108 dp adaptive canvas
N = 108 // CELL
OLIVE, TEAL, DIM = "#D8D48E", "#9CC9B8", "#E7E5D9"
rng = random.Random(7)

fg, bg, mono = [], [], []  # (x, y, colour, alpha)
cx, cy = 13.0, 13.8         # face centre in cells (inside the 66 dp safe zone)
rx, ry = 5.6, 7.2
eye_row = 12
for y in range(N):
    for x in range(N):
        dx, dy = (x - cx) / rx, (y - cy) / ry
        d = dx * dx + dy * dy
        # dim noise everywhere (background layer)
        if rng.random() < 0.45:
            bg.append((x, y, DIM, rng.choice([0.04, 0.07, 0.11])))
        band = eye_row <= y <= eye_row + 1 and 5 <= x <= 21
        if band:
            c = TEAL if rng.random() < 0.55 else OLIVE
            a = rng.choice([1.0, 1.0, 0.75, 0.5])
            fg.append((x, y, c, a)); mono.append((x, y, "#FFFFFF", a))
            continue
        if d <= 1.0:
            if y == eye_row + 2 and x in (10, 11, 15, 16):  # eyes peeking out under the band
                continue
            if y == 17 and 12 <= x <= 14:  # nose shadow
                if x == 13: continue
            if y == 19 and 11 <= x <= 15:  # mouth
                continue
            keep = 0.93 if d < 0.6 else 0.7   # the edge dissolves
            if rng.random() < keep:
                a = rng.choice([1.0, 0.85, 0.7, 0.55])
                fg.append((x, y, OLIVE, a)); mono.append((x, y, "#FFFFFF", a))
        elif d <= 1.9 and 4 <= x <= 22 and 4 <= y <= 23 and rng.random() < 0.13:
            a = rng.choice([0.5, 0.35, 0.25])  # loose pixels flying off the face
            fg.append((x, y, OLIVE, a)); mono.append((x, y, "#FFFFFF", a))

def vector(cells, path, base=None):
    groups = {}
    for x, y, c, a in cells:
        groups.setdefault((c, a), []).append(f"M{x*CELL},{y*CELL}h{CELL}v{CELL}h-{CELL}z")
    body = "\n".join(
        f'    <path android:fillColor="{c}" android:fillAlpha="{a}" android:pathData="{" ".join(p)}" />'
        for (c, a), p in sorted(groups.items()))
    if base:
        body = f'    <path android:fillColor="{base}" android:pathData="M0,0h108v108h-108z" />\n' + body
    open(path, "w").write(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/make_icon.py: a face made of pixel noise, glitch band over the eyes -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n' + body + "\n</vector>\n")

vector(fg, f"{OUT}/ic_launcher_foreground.xml")
vector(bg, f"{OUT}/ic_launcher_background.xml", base="#121210")
vector(mono, f"{OUT}/ic_launcher_monochrome.xml")

if len(sys.argv) < 3:
    sys.exit()

# Preview: full canvas, launcher circle mask, and a small size
S = 8
img = Image.new("RGB", (108 * S, 108 * S), "#121210")
d = ImageDraw.Draw(img, "RGBA")
def hexa(c, a): return tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)) + (int(a * 255),)
for cells in (bg, fg):
    for x, y, c, a in cells:
        d.rectangle([x * CELL * S, y * CELL * S, (x + 1) * CELL * S - 1, (y + 1) * CELL * S - 1], fill=hexa(c, a))
# launcher shows the middle 72 dp; circle mask
crop = img.crop((18 * S, 18 * S, 90 * S, 90 * S)).resize((288, 288), Image.LANCZOS)
mask = Image.new("L", crop.size, 0); ImageDraw.Draw(mask).ellipse([0, 0, 287, 287], fill=255)
round_ = Image.new("RGBA", crop.size, (0, 0, 0, 0)); round_.paste(crop.convert("RGBA"), mask=mask)
sheet = Image.new("RGB", (288 * 2 + 96 + 40, 300), "#2b2b2b")
sheet.paste(crop, (0, 6)); sheet.paste(round_, (300, 6), round_)
small = round_.resize((48, 48), Image.LANCZOS); sheet.paste(small, (600, 126), small)
sheet.save(sys.argv[2])
